#Даны два целых числа A и B (A < B). Вывести в порядке убывания все целые числа,
# расположенные между A и B (не включая числа A и B), а также количество N этих чисел.
# Запрашиваем ввод первого числа A
a = input("Введите первое число: ")
while type(a) != int:
    try:
        a = int(a)
    except ValueError:
        print("Неправильно ввели!")
        a = input("Введите первое число: ")

# Запрашиваем ввод второго числа B
b = input("Введите второе число: ")
while type(b) != int:
    try:
        b = int(b)
    except ValueError:
        print("Неправильно ввели!")
        b = input("Введите второе число: ")

# Проверка условия A < B (на случай, если пользователь ввел иначе)
if a >= b:
    print("Ошибка: Число a должно быть меньше b!")
else:
    # Начинаем с числа, которое меньше B на 1 (так как B не включается)
    c = b - 1
    n = 0

    print(f"Числа между {a} и {b} в порядке убывания:")

    # Цикл работает, пока текущее число строго больше A
    while c > a:
        print(c)
        c -= 1  # Уменьшаем число на 1 для движения вниз
        n += 1  # Увеличиваем счетчик количества чисел

    print('Количество чисел N:', n)
