# Ввести N чисел. Найти и вывести их среднее арифметическое.
n = int(input("Введите количество чисел N: "))
i = 0
t = 0

while i < n:
    num = float(input("Введите число: "))
    t += num
    i += 1

if n > 0:
    avg = t / n
    print("Среднее арифметическое:", avg)
else:
    print("Количество чисел должно быть больше 0")
