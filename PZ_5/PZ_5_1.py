# 1 звездочка, во второй - 2, в третьей -3, ..., в строке с номером m - m звездочек.
# Функция для построения изображения из звездочек
def p(m):
    for i in range(1, m + 1):
        print('*' * i)


# Ввод количества строк с обработкой ошибок
while True:
    try:
        m = int(input('Введите количество строк: '))
        if m > 0:
            break
        else:
            print('Число должно быть положительным!')
    except ValueError:
        print('Ошибка! Введите целое число.')

# Вызов функции
p(m)


def print_stars(m):
    i = 1
    while i <= m:
        print('*' * i)
        i += 1


try:
    m = int(input("Введите количество строк: "))

    if m <= 0:
        print("Число должно быть положительным")
    else:
        print_stars(m)

except ValueError:
    print("Ошибка! Введите целое число.")