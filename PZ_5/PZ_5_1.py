# Функция для построения изображения из звездочек
def stars(m):
    i = 1
    #цикл выполняется пока подходит к условию
    while i <= m:
        print('*' * i)
        i += 1
        #переменная для хранения
m = 0
#бесконечный цикл
while True:
    try:
        #считаем ввод и преобразовываем
        m = int(input("Введите количество строк: "))
    except ValueError:
        #обработка исключения
        print("Ошибка! Введите целое число.")

    if m <= 0:
        #проверка
        print("Число должно быть положительным")
    else:
        stars(m)
        #выход из цикла
        break


